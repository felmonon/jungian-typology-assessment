import { fireEvent, render, screen, within } from '@testing-library/react';
import { describe, expect, it, vi } from 'vitest';
import {
  ReportUnlockCard,
  StickyReportBar,
  buildReportUnlockSections,
} from '../../components/results/ReportUnlockCard';

const baseProps = {
  tierName: 'Insight',
  offerPrice: 'CA$7',
  regularPrice: 'CA$10',
  stackCodes: ['Se', 'Ti', 'Fe', 'Ni'],
  dominantLabel: 'Extraverted Sensation',
  inferiorLabel: 'Introverted Intuition',
  isOpening: false,
  checkoutError: null,
  onUnlock: vi.fn(),
  onSeeDetails: vi.fn(),
  onViewSample: vi.fn(),
};

describe('overview report unlock card', () => {
  it('describes all ten sections with the visitor’s own stack', () => {
    const sections = buildReportUnlockSections(baseProps);
    expect(sections).toHaveLength(10);
    expect(sections.find((section) => section.title === 'Grip sequence and recovery')?.detail).toContain('Ni');
    expect(sections.find((section) => section.title === 'Individuation path')?.detail)
      .toBe('Developing Introverted Intuition without abandoning Extraverted Sensation.');
  });

  it('offers a direct purchase with the price, terms, and an honest description', () => {
    const onUnlock = vi.fn();
    render(<ReportUnlockCard {...baseProps} onUnlock={onUnlock} />);
    expect(screen.getByText('Your Insight report · Se · Ti · Fe · Ni')).toBeVisible();
    expect(within(screen.getByRole('list', { name: 'The ten sections in your report' })).getAllByRole('listitem')).toHaveLength(10);
    expect(screen.getByText('CA$10')).toBeVisible();
    expect(screen.getByText(/One-time payment. No subscription./)).toBeVisible();
    expect(screen.getByText(/7-day refund policy/)).toBeVisible();
    expect(screen.getByText(/generated by AI from your assessment result/)).toBeVisible();
    expect(screen.getByText(/Your map, first read, and reflection stay free/)).toBeVisible();
    fireEvent.click(screen.getByRole('button', { name: 'Get my full report — CA$7' }));
    expect(onUnlock).toHaveBeenCalledTimes(1);
  });

  it('keeps the detail and sample routes available without starting checkout', () => {
    const onUnlock = vi.fn();
    const onSeeDetails = vi.fn();
    const onViewSample = vi.fn();
    render(<ReportUnlockCard {...baseProps} onUnlock={onUnlock} onSeeDetails={onSeeDetails} onViewSample={onViewSample} />);
    fireEvent.click(screen.getByRole('button', { name: 'See what my report adds' }));
    fireEvent.click(screen.getByRole('button', { name: 'Read a sample' }));
    expect(onSeeDetails).toHaveBeenCalledTimes(1);
    expect(onViewSample).toHaveBeenCalledTimes(1);
    expect(onUnlock).not.toHaveBeenCalled();
  });

  it('blocks repeat clicks while checkout opens and shows a recoverable error', () => {
    const onUnlock = vi.fn();
    const { rerender } = render(<ReportUnlockCard {...baseProps} onUnlock={onUnlock} isOpening />);
    const pending = screen.getByRole('button', { name: 'Checking availability…' });
    expect(pending).toBeDisabled();
    fireEvent.click(pending);
    expect(onUnlock).not.toHaveBeenCalled();
    rerender(<ReportUnlockCard {...baseProps} onUnlock={onUnlock} checkoutError="Secure checkout is temporarily unavailable." />);
    const alert = screen.getByRole('alert');
    expect(alert).toHaveTextContent('Secure checkout is temporarily unavailable.');
    expect(within(alert).getByRole('link', { name: 'Contact support' })).toHaveAttribute('href', expect.stringMatching(/^mailto:/));
    expect(screen.getByRole('button', { name: 'Get my full report — CA$7' })).toBeEnabled();
  });

  it('renders the not-ready email option only when one is supplied', () => {
    const { rerender } = render(<ReportUnlockCard {...baseProps} />);
    expect(screen.queryByTestId('unlock-not-ready')).toBeNull();
    rerender(<ReportUnlockCard {...baseProps} notReadyCapture={<p>Not ready to decide?</p>} />);
    expect(within(screen.getByTestId('unlock-not-ready')).getByText('Not ready to decide?')).toBeVisible();
  });
});

describe('small-screen report bar', () => {
  const barProps = {
    tierName: 'Insight',
    offerPrice: 'CA$7',
    isOpening: false,
    onUnlock: vi.fn(),
    onDismiss: vi.fn(),
  };

  it('renders nothing until it is made visible', () => {
    render(<StickyReportBar {...barProps} visible={false} />);
    expect(screen.queryByRole('complementary', { name: 'Get your report' })).toBeNull();
  });

  it('starts checkout or dismisses on request', () => {
    const onUnlock = vi.fn();
    const onDismiss = vi.fn();
    render(<StickyReportBar {...barProps} visible onUnlock={onUnlock} onDismiss={onDismiss} />);
    const bar = screen.getByRole('complementary', { name: 'Get your report' });
    expect(within(bar).getByText('Ten sections · CA$7 once')).toBeVisible();
    fireEvent.click(within(bar).getByRole('button', { name: 'Get it' }));
    expect(onUnlock).toHaveBeenCalledTimes(1);
    fireEvent.click(within(bar).getByRole('button', { name: 'Hide report bar' }));
    expect(onDismiss).toHaveBeenCalledTimes(1);
  });
});
